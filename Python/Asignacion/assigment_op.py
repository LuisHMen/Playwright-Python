"""
Operadores de asignación.
# Assiment operator: =, +=, -=, *=, /=, %=
a = a + 10 can be written as a += 10
"""
a = 70

a += 30 # a = a + 70
print("a += example: ", a)

a -= 20 # a = a - 20
print("a -= example: ", a)

a *= 2 # a = a * 2
print("a *= example: ", a)

a /= 8 # a = a / 8
print("a /= example: ", a)

a %= 6 # a = a % 6
print("a %= example: ", a)