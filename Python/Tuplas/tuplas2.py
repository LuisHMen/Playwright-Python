tupla1 = (1, 2, 3, 4, 5)
tupla2 = (True, False, True)
tupla3 = (1, 2, 3, "Luis", "Hernández", [4, 5, 6], True)

print(tupla1)
print(tupla2)

# Con doble corchete se puede acceder a los valores de la tupla que están entre corchetes.
# Por ejemplo: Un corchete muestra el arreglo completo.
print(tupla3[5])
# El segundo corchete indica la posición del arreglo que esta dentro de la tupla.
print(tupla3[5][1])